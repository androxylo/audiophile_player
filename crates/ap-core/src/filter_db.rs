impl AlbumTrackAnalysis {
    /// Convert a Schema-1 [`TrackDbEntry`] into a Schema-2 [`AlbumTrackAnalysis`] (used by
    /// scanner, learn-on-play, and `filters migrate`).
    pub fn from_schema1(entry: &TrackDbEntry, head_hash: Option<String>) -> Self {
        let why = why_for_rule(&entry.decision.rule).to_string();
        Self {
            suggested: entry.decision.filter.clone(),
            why,
            rule: entry.decision.rule.clone(),
            detector_version: entry.scan.detector_version,
            md5: entry.file.streaminfo_md5.clone(),
            size: entry.file.size,
            mtime_unix_s: entry.file.mtime_unix_s,
            seconds: entry.scan.duration_s,
            head_hash,
            sample_rate: entry.file.sample_rate,
            bits: entry.file.bits,
            effective_bits: entry.results.effective_bits,
            bandwidth_hz: entry.results.effective_bandwidth_hz,
            fake_hires: entry.results.upsampled_from_1x.clone(),
            effective_nyquist_hz: entry.results.effective_nyquist_hz,
            apodizing_needed: entry.results.apodizing_needed.clone(),
            apod_events: entry.results.apod_events,
            loud_and_clipped: entry.results.loud_and_clipped.clone(),
            hf_noise: entry.results.ultrasonic_noise_detected.clone(),
            lossy_origin: entry.results.lossy_origin_suspected,
            deemphasis: entry.results.deemphasis_flag,
            lufs: entry.results.integrated_lufs,
            sample_peak: entry.results.sample_peak,
            true_peak_dbtp: entry.results.true_peak_dbtp,
            clipped_runs: entry.results.clipped_runs,
            post_chain_peaks: entry.results.post_chain_peaks.clone(),
        }
    }

    /// True if this track's identity matches current `(md5, size, mtime)`.
    pub fn matches_identity(
        &self,
        cur_md5_hex: Option<&str>,
        cur_size: Option<u64>,
        cur_mtime_unix_s: Option<u64>,
    ) -> bool {
        matches_track_identity(
            self.md5.as_deref(),
            self.size,
            self.mtime_unix_s,
            cur_md5_hex,
            cur_size,
            cur_mtime_unix_s,
        )
    }

    /// Fast filesystem unchanged check (`size + mtime ±2 s`) for resumable scans.
    pub fn matches_size_mtime(&self, cur_size: u64, cur_mtime_unix_s: u64) -> bool {
        self.size == cur_size && self.mtime_unix_s.abs_diff(cur_mtime_unix_s) <= MTIME_TOLERANCE_SECS
    }

    /// Look up measured unity-gain post-chain peak `M` (dBFS) matching `key`.
    pub fn find_post_chain_peak(&self, key: &PostChainKey) -> Option<f64> {
        find_post_chain_peak(&self.post_chain_peaks, key)
    }

    /// Monotonically insert or raise `peak_dbfs` for `key`.
    pub fn upsert_post_chain_peak(&mut self, key: PostChainKey, peak_dbfs: f64, monotonic: bool) {
        upsert_post_chain_peak(&mut self.post_chain_peaks, key, peak_dbfs, monotonic);
    }
}

