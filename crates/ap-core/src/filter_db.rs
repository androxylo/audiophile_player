/// Schema version for per-album analysis files, `library.yaml`, and `relink-report.yaml`.
pub const FILTER_DB_SCHEMA_VERSION: u32 = 2;

/// Hard maximum size for a Schema-2 album analysis YAML file (256 KiB — comfortably covers
/// 100+ track box sets while bounding untrusted-file memory).
pub const MAX_ALBUM_YAML_BYTES: usize = 256 * 1024;

/// Maximum mirrored path component length before truncating with a deterministic hash suffix.
pub const MAX_MIRROR_COMPONENT_CHARS: usize = 120;

/// Stale lock age threshold (seconds) after which an orphaned `.lock` file is automatically purged.
const STALE_LOCK_MAX_AGE_SECS: u64 = 600;

/// Fixed plain-language explanation (`why:`) for each Ultimate Mode rule ID (Issue #17 §4.2).
pub fn why_for_rule(rule: &str) -> &'static str {
    let base = rule.split('(').next().unwrap_or(rule);
    match base {
        "rule_A_apodizing" => "pre-ringing events in source (apodizing needed)",
        "rule_L_loud_clipped" => "loud and clipped master (apodizing cleanup)",
        "rule_H_fake_hires_apodizing" => "fake hi-res with pre-ringing (apodizing at effective bandwidth)",
        "rule_H_fake_hires_steep" => "fake hi-res upsampled from 1x (filtered at effective bandwidth)",
        "rule_G_classical" => "clean 1x classical genre (long steep linear-phase)",
        "rule_G_rock_pop_electronic" => "clean 1x rock/pop/electronic genre (extended sharp passband)",
        "rule_G_jazz_acoustic" => "clean 1x jazz/acoustic genre (natural Gaussian long LP)",
        "rule_G_ambient_soundtrack" => "clean 1x ambient/soundtrack genre (natural Gaussian long LP)",
        "rule_R_1x_clean" => "clean 1x recording (long linear-phase Gaussian)",
        "rule_R_hires_clean" => "clean hi-res recording (gentle hi-res Gaussian)",
        "rule_R_hires_hf_noise" => "hi-res with ultrasonic noise shelf > 40 kHz (HF noise filter)",
        "native_8fs" => "native 352.8/384 kHz source (bit-exact pass-through)",
        "short_track_bypass" => "short track (< 30 s) using rate default",
        "cli_override" => "forced via --filter CLI option",
        "cli_streaming_guard" => "CLI filter substituted with streaming-safe Gaussian",
        "streaming_guard" | "streaming_guard_user" => "local-only filter substituted with streaming-safe Gaussian",
        "user_filter" => "explicit user track choice in my-filters.yaml",
        "user_folder" => "explicit user folder choice in my-filters.yaml",
        "user_tag" => "explicit AP_FILTER tag in FLAC metadata",
        "user_default" => "user default filter in my-filters.yaml",
        "user_phase_min" => "explicit user minimum-phase preference",
        "user_phase_ip" => "explicit user intermediate-phase preference",
        "throughput_fallback" => "CPU throughput fallback to lossless Gaussian",
        _ => "automatic filter selection",
    }
}

/// Parse a single-line YAML flow mapping `{ k1: v1, k2: "a, b: c" }` into `(key, raw_value)` pairs.
pub(crate) fn parse_flow_map(raw: &str, line_no: usize) -> Result<Vec<(String, String)>, String> {
    let t = raw.trim();
    let Some(inner) = t.strip_prefix('{').and_then(|s| s.strip_suffix('}')) else {
        return Err(format!("YAML line {line_no}: expected flow map '{{ ... }}', got '{t}'"));
    };
    let mut items = Vec::new();
    let mut start = 0usize;
    let mut in_double = false;
    let mut in_single = false;
    let mut escape = false;

    let push_pair = |seg: &str, out: &mut Vec<(String, String)>| -> Result<(), String> {
        let s = seg.trim();
        if s.is_empty() {
            return Ok(());
        }
        let Some((k, v)) = split_yaml_key_val(s) else {
            return Err(format!("YAML line {line_no}: expected 'key: value' inside flow map, got '{s}'"));
        };
        out.push((parse_yaml_string(k)?, v.trim().to_string()));
        Ok(())
    };

    for (i, ch) in inner.char_indices() {
        if escape {
            escape = false;
            continue;
        }
        if ch == '\\' && in_double {
            escape = true;
            continue;
        }
        if ch == '"' && !in_single {
            in_double = !in_double;
            continue;
        }
        if ch == '\'' && !in_double {
            in_single = !in_single;
            continue;
        }
        if ch == ',' && !in_double && !in_single {
            push_pair(&inner[start..i], &mut items)?;
            start = i + 1;
        }
    }
    if in_double || in_single {
        return Err(format!("YAML line {line_no}: unterminated quote in flow map"));
    }
    push_pair(&inner[start..], &mut items)?;
    Ok(items)
}

/// Normalize a relative POSIX-style library path (`/` separators, no leading/trailing `/`, no `.` or `..`).
pub fn normalize_rel_path(raw: &str) -> String {
    let replaced = raw.trim().replace('\\', "/");
    let parts: Vec<&str> = replaced
        .split('/')
        .filter(|p| !p.is_empty() && *p != ".")
        .collect();
    parts.join("/")
}

/// Resolve a filesystem path onto extended-length `\\?\` form on Windows when long (> 240 chars).
pub fn extended_io_path(path: &Path) -> PathBuf {
    #[cfg(windows)]
    {
        let s = path.to_string_lossy();
        if s.len() > 240 && !s.starts_with(r"\\?\") {
            if let Some(unc_rest) = s.strip_prefix(r"\\") {
                return PathBuf::from(format!(r"\\?\UNC\{unc_rest}"));
            }
            if s.len() >= 3 && s.as_bytes()[1] == b':' {
                return PathBuf::from(format!(r"\\?\{s}"));
            }
        }
    }
    path.to_path_buf()
}

/// Sanitize a single path component for the mirrored analysis tree, capping at
/// [`MAX_MIRROR_COMPONENT_CHARS`] and appending a deterministic short FNV hash suffix only when
/// truncated or when illegal filesystem characters had to be escaped.
pub fn sanitize_mirror_component(raw: &str) -> String {
    let mut cleaned = String::with_capacity(raw.len());
    let mut modified = false;
    for ch in raw.chars() {
        let illegal = matches!(ch, '<' | '>' | ':' | '"' | '/' | '\\' | '|' | '?' | '*')
            || (ch as u32) < 0x20;
        if illegal {
            cleaned.push('_');
            modified = true;
        } else {
            cleaned.push(ch);
        }
    }
    // Trim trailing spaces/dots (illegal on Windows filenames).
    let trimmed = cleaned.trim_end_matches([' ', '.']);
    if trimmed.len() != cleaned.len() {
        modified = true;
    }
    let mut base = if trimmed.is_empty() {
        modified = true;
        "_dir".to_string()
    } else {
        trimmed.to_string()
    };

    // Guard Windows reserved DOS device names (CON, PRN, AUX, NUL, COM1..9, LPT1..9).
    let upper = base.to_ascii_uppercase();
    let is_reserved = matches!(upper.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || (upper.len() == 4
            && (upper.starts_with("COM") || upper.starts_with("LPT"))
            && upper.as_bytes()[3].is_ascii_digit()
            && upper.as_bytes()[3] != b'0');
    if is_reserved {
        modified = true;
    }

    let char_count = base.chars().count();
    if char_count > MAX_MIRROR_COMPONENT_CHARS {
        let keep = MAX_MIRROR_COMPONENT_CHARS.saturating_sub(9);
        base = base.chars().take(keep).collect();
        modified = true;
    }

    if modified {
        let short_hash = &fnv1a_128_hex(raw.as_bytes())[..8];
        format!("{base}_{short_hash}")
    } else {
        base
    }
}

/// `filterdb/library.yaml` — named library roots, detector version, and last scan summary.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct LibraryManifest {
    pub schema: u32,
    /// Named roots (`"main" -> "D:/Music"`, `"nas" -> "//nas/flac"`), sorted deterministically.
    pub roots: BTreeMap<String, String>,
    pub detector_version: u32,
    pub last_scan_started_unix_s: u64,
    pub last_scan_finished_unix_s: u64,
    pub last_scan_folders: u64,
    pub last_scan_files: u64,
    pub suggested_changed_since_previous: u64,
}

impl LibraryManifest {
    pub fn new(detector_version: u32) -> Self {
        Self {
            schema: FILTER_DB_SCHEMA_VERSION,
            roots: BTreeMap::new(),
            detector_version,
            ..Self::default()
        }
    }

    /// Register or update a named music root (normalizing slashes and stripping `\\?\`).
    pub fn upsert_root(&mut self, name: impl Into<String>, path: &Path) {
        if self.schema == 0 {
            self.schema = FILTER_DB_SCHEMA_VERSION;
        }
        self.roots
            .insert(name.into(), clean_root_path_string(path));
    }

    /// Resolve an absolute local path against configured named roots (longest-prefix match).
    /// Returns `(root_name, rel_folder, file_name)`.
    pub fn resolve_track_path(&self, abs_path: &Path) -> Option<(String, String, String)> {
        let file_name = abs_path.file_name()?.to_string_lossy().into_owned();
        let parent = abs_path.parent()?;
        let (root_name, rel_folder) = self.resolve_folder_path(parent)?;
        Some((root_name, rel_folder, file_name))
    }

    /// Resolve an absolute folder path against configured named roots (longest-prefix match).
    /// Returns `(root_name, rel_folder)` where `rel_folder` is `""` for the root itself.
    pub fn resolve_folder_path(&self, abs_folder: &Path) -> Option<(String, String)> {
        let norm_target = normalize_path_for_eq(&abs_folder.to_string_lossy());
        let target_slash = norm_target.replace('\\', "/").trim_end_matches('/').to_string();

        let mut best: Option<(usize, String, String)> = None;
        for (name, root_raw) in &self.roots {
            let norm_root = normalize_path_for_eq(root_raw)
                .replace('\\', "/")
                .trim_end_matches('/')
                .to_string();
            if norm_root.is_empty() {
                continue;
            }
            if target_slash == norm_root {
                let score = norm_root.len();
                if best.as_ref().is_none_or(|(b, _, _)| score > *b) {
                    best = Some((score, name.clone(), String::new()));
                }
            } else if target_slash.len() > norm_root.len()
                && target_slash.starts_with(&norm_root)
                && target_slash.as_bytes()[norm_root.len()] == b'/'
            {
                // Preserve original case of the relative suffix from `abs_folder`!
                let orig_abs = abs_folder.to_string_lossy().replace('\\', "/");
                let orig_trimmed = orig_abs.trim_end_matches('/');
                let orig_no_verb = orig_trimmed
                    .strip_prefix("//?/UNC/")
                    .map(|r| format!("//{r}"))
                    .or_else(|| orig_trimmed.strip_prefix("//?/").map(str::to_string))
                    .unwrap_or_else(|| orig_trimmed.to_string());
                let rel_orig = if orig_no_verb.len() > norm_root.len() {
                    orig_no_verb[norm_root.len()..].trim_start_matches('/')
                } else {
                    target_slash[norm_root.len()..].trim_start_matches('/')
                };
                let rel = normalize_rel_path(rel_orig);
                let score = norm_root.len();
                if best.as_ref().is_none_or(|(b, _, _)| score > *b) {
                    best = Some((score, name.clone(), rel));
                }
            }
        }
        best.map(|(_, name, rel)| (name, rel))
    }

    /// Resolve a `root:rel/path` key (or bare `rel/path` defaulting to `"main"`) back to an
    /// absolute filesystem path if the root is registered.
    pub fn to_abs_path(&self, key: &str) -> Option<PathBuf> {
        let (root_name, rel) = split_root_key(key);
        let root_base = self.roots.get(root_name)?;
        let mut out = PathBuf::from(root_base);
        for seg in rel.split('/').filter(|s| !s.is_empty()) {
            out.push(seg);
        }
        Some(out)
    }

    pub fn to_yaml_string(&self) -> String {
        let mut s = String::with_capacity(512);
        s.push_str("# Machine-written by `audiophile-player scan`.\n");
        s.push_str(&format!("schema: {}\n", FILTER_DB_SCHEMA_VERSION));
        if self.roots.is_empty() {
            s.push_str("roots: {}\n");
        } else {
            s.push_str("roots:\n");
            for (k, v) in &self.roots {
                s.push_str(&format!("  {}: {}\n", k, yaml_quote(v)));
            }
        }
        s.push_str(&format!("detector_version: {}\n", self.detector_version));
        s.push_str("last_scan:\n");
        s.push_str(&format!("  started_unix_s: {}\n", self.last_scan_started_unix_s));
        s.push_str(&format!("  finished_unix_s: {}\n", self.last_scan_finished_unix_s));
        s.push_str(&format!("  folders: {}\n", self.last_scan_folders));
        s.push_str(&format!("  files: {}\n", self.last_scan_files));
        s.push_str(&format!(
            "  suggested_changed_since_previous: {}\n",
            self.suggested_changed_since_previous
        ));
        s
    }

    pub fn from_yaml_str(input: &str) -> Result<Self, String> {
        if input.len() > MAX_ALBUM_YAML_BYTES {
            return Err(format!("library.yaml exceeds {MAX_ALBUM_YAML_BYTES} bytes"));
        }
        let text = input.strip_prefix('\u{feff}').unwrap_or(input);
        let mut out = LibraryManifest::new(0);
        let mut saw_schema = false;
        let mut section = "";

        for (idx, raw_line) in text.lines().enumerate() {
            let line_no = idx + 1;
            let stripped = strip_yaml_comment(raw_line);
            let trimmed = stripped.trim();
            if trimmed.is_empty() {
                continue;
            }
            check_yaml_line_safety(raw_line, trimmed, line_no, "library.yaml")?;
            let indent = raw_line.len() - raw_line.trim_start_matches(' ').len();
            let Some((k_raw, v_raw)) = split_yaml_key_val(trimmed) else {
                return Err(format!("library.yaml line {line_no}: expected 'key: value'"));
            };
            let key = parse_yaml_string(k_raw)?;
            let val = v_raw.trim();
            if indent == 0 {
                match key.as_str() {
                    "schema" => {
                        let ver = val.parse::<u32>().map_err(|_| {
                            format!("library.yaml line {line_no}: invalid schema '{val}'")
                        })?;
                        if ver != FILTER_DB_SCHEMA_VERSION {
                            return Err(format!(
                                "library.yaml unsupported schema {ver} (expected {FILTER_DB_SCHEMA_VERSION})"
                            ));
                        }
                        out.schema = ver;
                        saw_schema = true;
                        section = "";
                    }
                    "roots" => {
                        section = "roots";
                        if val.starts_with('{') {
                            for (rk, rv) in parse_flow_map(val, line_no)? {
                                out.roots.insert(rk, parse_yaml_string(&rv)?);
                            }
                            section = "";
                        }
                    }
                    "detector_version" => {
                        out.detector_version = val.parse::<u32>().map_err(|_| {
                            format!("library.yaml line {line_no}: invalid detector_version '{val}'")
                        })?;
                        section = "";
                    }
                    "last_scan" => section = "last_scan",
                    _ => section = "",
                }
            } else if section == "roots" {
                out.roots.insert(key, parse_yaml_string(val)?);
            } else if section == "last_scan" {
                match key.as_str() {
                    "started_unix_s" => {
                        out.last_scan_started_unix_s = val.parse().unwrap_or(0);
                    }
                    "finished_unix_s" => {
                        out.last_scan_finished_unix_s = val.parse().unwrap_or(0);
                    }
                    "folders" => out.last_scan_folders = val.parse().unwrap_or(0),
                    "files" => out.last_scan_files = val.parse().unwrap_or(0),
                    "suggested_changed_since_previous" => {
                        out.suggested_changed_since_previous = val.parse().unwrap_or(0);
                    }
                    _ => {}
                }
            }
        }
        if !saw_schema {
            return Err("library.yaml missing required 'schema: 2' header".to_string());
        }
        Ok(out)
    }
}

/// Split `"root:rel/path"` into `("root", "rel/path")` (defaults to `("main", key)` when no root
/// prefix is given; Windows drive letters like `"D:/..."` are NOT split as root names).
pub fn split_root_key(key: &str) -> (&str, String) {
    let trimmed = key.trim();
    if let Some((prefix, rest)) = trimmed.split_once(':') {
        // A valid root name is >= 2 ASCII alphanumeric/underscore/hyphen chars (not a 1-letter drive).
        if prefix.len() >= 2
            && prefix
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
        {
            return (prefix, normalize_rel_path(rest));
        }
    }
    ("main", normalize_rel_path(trimmed))
}

