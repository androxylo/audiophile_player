//! Schema-2 Per-Album Filter Analysis Database (`FILTER_DATABASE_RESEARCH.md` / Issue #17).
//!
//! Architecture:
//! - **Machine-owned analysis** lives under `%APPDATA%\audiophile-player\filterdb\`:
//!   - `library.yaml`: named library roots (`main`, `nas`, ...), detector version, scan stats.
//!   - `analysis/<root>/<relative-folder>.yaml`: one human-readable YAML file per album folder
//!     containing all audio tracks in that folder (headline `suggested`, plain-language `why`,
//!     `rule`, compact flow-style metrics, and full 6-tuple `post_chain_peaks`).
//!   - `relink-report.yaml`: move/rename suggestions generated by `scan` for entries referenced
//!     in user-owned `my-filters.yaml` (which `scan` NEVER writes).
//! - **Zero-dependency hardened parser**: rejects `!` tags, `&` anchors, `*` aliases, `<<:` merge
//!   keys, tabs, unsupported schemas, and oversized files (`> 256 KiB`).
//! - **Windows long-path safe**: mirrors folder components capped at 120 chars (with deterministic
//!   short FNV hash suffix on truncation or illegal-character sanitization) and uses extended-length
//!   (`\\?\`) paths internally on Windows when paths exceed 240 chars.
//! - **Non-blocking per-folder `.lock`**: serializes `scan` and playback learn-on-play without
//!   ever stalling playback (learn-on-play skips writing if the folder lock is held).

